package build

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"

	"github.com/evanw/esbuild/pkg/api"
)

// puzzleWorkDir is the compiler's per-app scratch directory under the app root.
// It is a DOT directory on purpose: plugin.skipScanDir prunes dot-directories
// from the usage scan, and `puzzle dev` only ever watches app/ (plus a
// root-level public/), so generating files here can never feed a rebuild loop.
const puzzleWorkDir = ".puzzle"

// fixturesEntryDir is the subdirectory of puzzleWorkDir that holds the generated
// `--fixtures` wrapper entry.
const fixturesEntryDir = "fixtures"

// fixturesConfigCandidates are the app-relative paths a `--fixtures` build looks
// for, JavaScript first (matching findStaticModule's preference).
var fixturesConfigCandidates = []string{"app/fixtures.js", "app/fixtures.ts"}

// fixturesWrapper is the generated `--fixtures` entry (D98) and the bookkeeping
// the build needs around it.
type fixturesWrapper struct {
	// Entry is the module esbuild bundles instead of app/app.js. Its BASE NAME is
	// app.js so the output still lands at dist/app.js.
	Entry string
	// wiring is the sibling module that installs the fixtures runtime; appEntry is
	// the app's real entry. Both are imported by Entry, and both are forced
	// side-effectful by Plugin (see below).
	wiring   string
	appEntry string
	// CreatedWorkDir records whether generating the wrapper created <root>/.puzzle
	// — the only case in which a one-shot build may remove it again.
	CreatedWorkDir bool
}

// findFixturesConfig returns the absolute path of the app's fixtures config file
// (app/fixtures.js, else app/fixtures.ts), or "" when neither exists.
func findFixturesConfig(absRoot string) string {
	for _, candidate := range fixturesConfigCandidates {
		path := filepath.Join(absRoot, filepath.FromSlash(candidate))
		if FileExists(path) {
			return path
		}
	}
	return ""
}

// errMissingFixturesConfig is the error a `--fixtures` build fails with when the
// app has no fixtures config to install.
func errMissingFixturesConfig() error {
	return fmt.Errorf(
		"--fixtures requires app/fixtures.js (or .ts) — it should default-export { seed, mock, setup }",
	)
}

// fixturesConflictError reports that `--fixtures` was combined with a prerender
// output mode. The two are unsupported together: prerendering executes the app
// in Node at build time, so an installed fixtures module would bake generated
// records into the emitted HTML while the shipped bundle generated its own on
// load.
func fixturesConflictError(mode string) error {
	return fmt.Errorf(
		"--fixtures conflicts with output: '%s' — prerendered pages and fixtures are unsupported together; drop --fixtures, or build without --%s",
		mode, mode,
	)
}

// prepareFixtures validates the `--fixtures` request for the app at absRoot and
// generates its wrapper entry. mode is the resolved output mode (see
// resolveOutputMode); a prerender mode is rejected here rather than after a
// pointless bundle pass.
func prepareFixtures(absRoot, mode string) (fixturesWrapper, error) {
	if mode != "" {
		return fixturesWrapper{}, fixturesConflictError(mode)
	}
	configPath := findFixturesConfig(absRoot)
	if configPath == "" {
		return fixturesWrapper{}, errMissingFixturesConfig()
	}
	return generateFixturesEntry(absRoot, configPath)
}

// generateFixturesEntry writes the two-file `--fixtures` wrapper under
// <absRoot>/.puzzle/fixtures/.
//
// The wrapper lives under the APP ROOT, not a temp dir, so that a published app
// resolves '@magic-spells/puzzle/fixtures' by the ordinary node_modules walk —
// .puzzle/fixtures/ → .puzzle/ → the project root. Only an in-repo app (where
// the runtime is not installed) needs the alias configureRuntime adds.
//
// Two files, not one, because static imports HOIST: within a single module the
// `installFixtures(config)` call would run AFTER the app module's body,
// installing the prototype patches too late to matter. Only a DEPENDENCY
// module's body is guaranteed to run before the importing module's body, so the
// wiring gets its own module and the entry imports it first.
func generateFixturesEntry(absRoot, configPath string) (fixturesWrapper, error) {
	w := fixturesWrapper{appEntry: filepath.Join(absRoot, "app", "app.js")}

	workDir := filepath.Join(absRoot, puzzleWorkDir)
	if _, err := os.Stat(workDir); err != nil {
		if !os.IsNotExist(err) {
			return fixturesWrapper{}, fmt.Errorf("checking %s: %w", workDir, err)
		}
		w.CreatedWorkDir = true
	}

	dir := filepath.Join(workDir, fixturesEntryDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return w, fmt.Errorf("creating the --fixtures wrapper dir %s: %w", dir, err)
	}

	w.wiring = filepath.Join(dir, "wiring.js")
	w.Entry = filepath.Join(dir, "app.js")

	wiring := "// Generated by puzzle --fixtures (D98). Do not edit.\n" +
		"import { installFixtures } from '@magic-spells/puzzle/fixtures';\n" +
		"import config from " + jsSpecifier(configPath) + ";\n" +
		"installFixtures(config);\n"
	// Absolute specifiers on BOTH imports (not './wiring.js') so Plugin's resolver
	// can match them exactly; see its comment for why they have to be matched.
	wrapper := "// Generated by puzzle --fixtures (D98). Do not edit.\n" +
		"import " + jsSpecifier(w.wiring) + ";\n" +
		"import " + jsSpecifier(w.appEntry) + ";\n"

	if err := os.WriteFile(w.wiring, []byte(wiring), 0o644); err != nil {
		return w, fmt.Errorf("writing the --fixtures wiring module: %w", err)
	}
	if err := os.WriteFile(w.Entry, []byte(wrapper), 0o644); err != nil {
		return w, fmt.Errorf("writing the --fixtures wrapper entry: %w", err)
	}
	return w, nil
}

// Plugin forces the wrapper's two imports to count as side-effectful.
//
// Both are BARE imports — no binding is used — so esbuild keeps them only if the
// modules are believed to have side effects, and the nearest package.json
// decides that. `@magic-spells/puzzle` itself declares "sideEffects": false, so
// any app built INSIDE the framework repo (the examples, the compiler's own
// tests) resolves that field for both the generated wrapper and app/app.js and
// drops both imports — an empty bundle, silently. Under a normal build app/app.js
// is the ENTRY POINT, which esbuild never drops, so the hazard is unique to this
// wrapper. Overriding SideEffects at resolve time removes the dependence on
// whatever package.json happens to sit above the app.
func (w fixturesWrapper) Plugin() api.Plugin {
	filter := "^(" +
		regexp.QuoteMeta(filepath.ToSlash(w.wiring)) + "|" +
		regexp.QuoteMeta(filepath.ToSlash(w.appEntry)) + ")$"
	return api.Plugin{
		Name: "puzzle-fixtures-entry",
		Setup: func(build api.PluginBuild) {
			build.OnResolve(api.OnResolveOptions{Filter: filter}, func(args api.OnResolveArgs) (api.OnResolveResult, error) {
				return api.OnResolveResult{
					Path:        filepath.FromSlash(args.Path),
					SideEffects: api.SideEffectsTrue,
				}, nil
			})
		},
	}
}

// jsSpecifier renders an absolute path as a quoted, forward-slashed import
// specifier (see absModuleImport for the same slash normalization). Quoting is
// strconv.Quote rather than a hand-written pair of apostrophes so a path
// containing a quote or a backslash cannot produce broken JavaScript.
func jsSpecifier(path string) string {
	return strconv.Quote(filepath.ToSlash(path))
}

// cleanupFixturesWorkDir removes <absRoot>/.puzzle after a one-shot `--fixtures`
// build, but ONLY when this build created the directory AND it still holds
// nothing but the generated fixtures/ subdir. Anything else there is a user's (or
// another tool's), and deleting it would be destructive. Failures are ignored: a
// leftover scratch dir must never turn a successful build into a failed one.
//
// The dev/watch path deliberately does not call this — its wrapper is generated
// once at builder construction and has to survive for the process lifetime.
func cleanupFixturesWorkDir(absRoot string, created bool) {
	if !created {
		return
	}
	workDir := filepath.Join(absRoot, puzzleWorkDir)
	entries, err := os.ReadDir(workDir)
	if err != nil {
		return
	}
	for _, e := range entries {
		if e.Name() != fixturesEntryDir || !e.IsDir() {
			return
		}
	}
	_ = os.RemoveAll(workDir)
}
